// Narrow IPC bridge for the desktop chat, settings and timetable pages.
'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const listen = (channel, callback) => ipcRenderer.on(channel, (_event, data) => callback(data));

contextBridge.exposeInMainWorld('electronAPI', {
  getConfig: () => ipcRenderer.invoke('get-config'),
  getSettingsConfig: () => ipcRenderer.invoke('settings-get-config'),
  saveConfig: config => ipcRenderer.invoke('save-config', config),
  onConfigUpdated: callback => listen('config-updated', callback),
  onSettingsSection: callback => listen('settings-section', callback),
  campusDebugInfo: () => ipcRenderer.invoke('campus-debug-info'),
  campusDebugOpen: () => ipcRenderer.invoke('campus-debug-open'),
  campusDebugExport: () => ipcRenderer.invoke('campus-debug-export'),
  campusGetSession: mode => ipcRenderer.invoke('campus-get-session', mode),
  campusNewConversation: mode => ipcRenderer.invoke('campus-new-conversation', mode),
  switchChatMode: mode => ipcRenderer.invoke('chat-switch-mode', mode),
  cancelChat: mode => ipcRenderer.invoke('chat-cancel', mode),
  onChatProgress: callback => listen('chat-progress', callback),
  campusSend: payload => ipcRenderer.send('campus-chat-send', payload),
  onCampusReply: callback => listen('campus-reply', callback),
  onCampusError: callback => listen('campus-error', callback),
  campusGetMemory: () => ipcRenderer.invoke('campus-memory-get'),
  campusUpdateMemory: data => ipcRenderer.invoke('campus-memory-update', data),
  campusClearMemory: () => ipcRenderer.invoke('campus-memory-clear'),
  campusSummarizeMemory: () => ipcRenderer.invoke('campus-memory-summarize'),
  onCampusMemoryUpdated: callback => listen('campus-memory-updated', callback),
  openTimetableWindow: () => ipcRenderer.send('open-timetable-window'),
  campusGetTimetable: () => ipcRenderer.invoke('campus-timetable-get'),
  campusSelectTimetable: () => ipcRenderer.invoke('campus-timetable-select'),
  campusTimetableSource: () => ipcRenderer.invoke('campus-timetable-source'),
  campusParseTimetable: data => ipcRenderer.invoke('campus-timetable-parse', data),
  campusSaveTimetable: data => ipcRenderer.invoke('campus-timetable-save', data),
  campusClearTimetable: () => ipcRenderer.invoke('campus-timetable-clear'),
  campusCancelTimetable: () => ipcRenderer.invoke('campus-timetable-cancel'),
  synthesizeSpeech: text => ipcRenderer.invoke('speech-synthesize', text),
  stopSpeech: () => ipcRenderer.send('speech-stop'),
  setIgnoreMouse: ignore => ipcRenderer.send('set-ignore-mouse', ignore),
  windowDrag: (dx, dy) => ipcRenderer.send('window-drag', dx, dy),
  windowResize: scale => ipcRenderer.send('window-resize', scale),
  resizeToContent: (width, height) => ipcRenderer.invoke('resize-to-content', width, height),
  showContextMenu: () => ipcRenderer.send('show-context-menu'),
  onPortraitAction: callback => listen('portrait-action', callback),
  onPlayExpression: callback => listen('play-expression', callback),
  onResetExpression: callback => listen('reset-expression', callback),
  onPlayMotion: callback => ipcRenderer.on('play-motion', (_event, index, name) => callback(index, name)),
  onStopMotion: callback => listen('stop-motion', callback),
  openSettingsWindow: section => ipcRenderer.send('open-settings-window', section),
  openExternal: url => ipcRenderer.invoke('open-external', url),
  chooseCustomImage: () => ipcRenderer.invoke('choose-custom-image'),
  quitApp: () => ipcRenderer.send('quit-app'),
});
